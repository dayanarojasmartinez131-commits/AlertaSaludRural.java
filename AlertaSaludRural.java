    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String buscar = txtBuscar.getText().trim().toLowerCase();

    if (buscar.isEmpty()) {
        JOptionPane.showMessageDialog(this,"Ingrese un dato para buscar.");
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) tblCasos.getModel();

    boolean encontrado = false;

    for (int fila = 0; fila < modelo.getRowCount(); fila++) {

        boolean coincide = false;

        // Buscar en todas las columnas
        for (int columna = 0;
             columna < modelo.getColumnCount();
             columna++) {

            Object dato = modelo.getValueAt(fila, columna);

            if (dato != null &&
                dato.toString().toLowerCase().contains(buscar)) {

                coincide = true;
                break;
            }
        }

        if (coincide) {

            // Seleccionar la fila encontrada
            tblCasos.setRowSelectionInterval(fila, fila);

            // Obtener los datos de la fila
            String distrito = modelo.getValueAt(fila, 0).toString();
            String zona = modelo.getValueAt(fila, 1).toString();
            String fecha = modelo.getValueAt(fila, 2).toString();
            String paciente = modelo.getValueAt(fila, 3).toString();
            String necesidad = modelo.getValueAt(fila, 4).toString();

            // Mostrar los datos encontrados
            JOptionPane.showMessageDialog(this,
                "REGISTRO ENCONTRADO\n\n"
                + "Distrito: " + distrito + "\n"
                + "Zona: " + zona + "\n"
                + "Fecha: " + fecha + "\n"
                + "Paciente: " + paciente + "\n"
                + "Necesidad: " + necesidad,
                "Resultado de búsqueda",
                JOptionPane.INFORMATION_MESSAGE);

            encontrado = true;
            break;
        }
    }

    if (!encontrado) {

        JOptionPane.showMessageDialog(this,"No se encontró ningún registro.","Búsqueda",
            JOptionPane.INFORMATION_MESSAGE);
    }

    }//GEN-LAST:event_btnBuscarActionPerformed

